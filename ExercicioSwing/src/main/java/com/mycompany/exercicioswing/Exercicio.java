        int linha = tabelaRelatorio.getRowCount() - 1;
        int coluna = 0;
        tabelaRelatorio.setValueAt(nome, linha, coluna++);
        tabelaRelatorio.setValueAt(cidade, linha, coluna++);
        tabelaRelatorio.setValueAt(SO, linha, coluna++);
