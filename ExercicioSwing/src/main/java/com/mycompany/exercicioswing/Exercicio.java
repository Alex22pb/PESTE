    private void jButtonCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCadastrarActionPerformed
        String nome = TextDigitarNome.getText();
        String cidade = ComboCidade.getSelectedItem().toString();
        String versao = ComboVersao.getSelectedItem().toString();
        String SO = "";
        String processador = "";
        String hd = "";
        List listRAM = listaRAM.getSelectedValuesList();

        if (buttonGroup1.getSelection().getMnemonic() == 'I') {
            processador = "Intel";
        } else {
            processador = "AMD";
        }

        if (ButtonGroupSist.getSelection().getMnemonic() == 'W') {
            SO = "Windows";
        } else {
            SO = "Linux";
        }

        if (buttonGroupHD.getSelection().getMnemonic() == '1') {
            hd = "1 TB";
        } else if (buttonGroupHD.getSelection().getMnemonic() == '5') {
            hd = "500 GB";
        } else {
            hd = "320 GB";
        }
        
        if (validarCampo()) {
            inserirRelatorio(nome, cidade, versao, SO, processador, hd, listRAM);
            ComboCidade.setSelectedItem("Colatina");
            ComboVersao.setEnabled(false);
            ComboVersao.removeAllItems();
            Check500.setSelected(true);
            TextDigitarNome.setText("");
            ButtonGroupSist.clearSelection();
            buttonGroup1.clearSelection();
            listaRAM.clearSelection();
            
        }
       
    }//GEN-LAST:event_jButtonCadastrarActionPerformed
    
    private boolean validarCampo(){
        LabelNome.setForeground(Color.black);
        String msgErro =  "";
        if(TextDigitarNome.getText().isEmpty()){
            msgErro = msgErro + "Digite um nome válido.\n";
            LabelNome.setForeground(Color.red);
        }
        
        if(msgErro.isEmpty()){
            return true;
        }else{
            JOptionPane.showMessageDialog(this, msgErro, "Cadastro de nome", JOptionPane.INFORMATION_MESSAGE);
            return false;
        }
    }
    
    private void menuExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuExcluirActionPerformed
        int linha = tabelaRelatorio.getSelectedRow();
        if(linha >= 0){
            if (JOptionPane.showConfirmDialog(this, "Deseja excluir essa linha?") == JOptionPane.YES_OPTION) {
                ((DefaultTableModel) tabelaRelatorio.getModel()).removeRow(linha);
            }
        }
    }//GEN-LAST:event_menuExcluirActionPerformed

    private void menuAlterarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_menuAlterarActionPerformed
        int linha = tabelaRelatorio.getSelectedRow();
        int coluna = 0;
        if(linha >= 0){
            if(JOptionPane.showConfirmDialog(this, "Deseja alterar essa linha?") == JOptionPane.YES_OPTION){
                TextDigitarNome.setText(tabelaRelatorio.getValueAt(linha, coluna++).toString());
                ComboCidade.setSelectedItem(tabelaRelatorio.getValueAt(linha, coluna++).toString());
                if(tabelaRelatorio.getValueAt(linha, coluna++).toString().equals("Windows")){
                    ButtonWindows.setSelected(true);
                    ButtonWindowsActionPerformed(evt);
                    ComboVersao.setSelectedItem(tabelaRelatorio.getValueAt(linha, coluna++).toString());
                }else{
                    ButtonLinux.setSelected(true);
                    ButtonLinuxActionPerformed(evt);
                    ComboVersao.setSelectedItem(tabelaRelatorio.getValueAt(linha, coluna++).toString());
                }
                if(tabelaRelatorio.getValueAt(linha, coluna++).toString().equals("AMD")){
                    buttonAmd.setSelected(true);
                }else{
                    buttonIntel.setSelected(true);
                }
                if(tabelaRelatorio.getValueAt(linha, coluna).toString().equals("320 GB")){
                    Check320.setSelected(true);
                }else if(tabelaRelatorio.getValueAt(linha, coluna).toString().equals("500 GB")){
                    Check500.setSelected(true);
                }else{
                    Check1TB.setSelected(true);
                }
                
                listaRAM.setSelectedValue(tabelaRelatorio.getValueAt(linha, ++coluna).toString().replaceAll("[\\[\\]]", ""), true);

                ((DefaultTableModel) tabelaRelatorio.getModel()).removeRow(linha);
            }
        }
    }//GEN-LAST:event_menuAlterarActionPerformed

